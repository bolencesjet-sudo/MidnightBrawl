CREATE TABLE IF NOT EXISTS users (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(80) NOT NULL,
 email VARCHAR(190) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role ENUM('organizer','referee','player') NOT NULL DEFAULT 'player',
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS events (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 name VARCHAR(120) NOT NULL,
 game VARCHAR(100) NOT NULL,
 team_size TINYINT UNSIGNED NOT NULL,
 max_teams SMALLINT UNSIGNED NOT NULL,
 formation ENUM('captain','free','random') NOT NULL,
 format ENUM('single','double') NOT NULL,
 race_to TINYINT UNSIGNED NOT NULL,
 deadline DATETIME NOT NULL,
 roles JSON NOT NULL,
 locked BOOLEAN NOT NULL DEFAULT 0,
 demo BOOLEAN NOT NULL DEFAULT 0,
 draft_pick INT UNSIGNED NOT NULL DEFAULT 0,
 created_by INT UNSIGNED NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (created_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS players (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 event_id INT UNSIGNED NOT NULL,
 user_id INT UNSIGNED NULL,
 display_name VARCHAR(80) NOT NULL,
 game_id VARCHAR(100) NOT NULL,
 primary_role VARCHAR(60) NOT NULL,
 secondary_role VARCHAR(60) NOT NULL DEFAULT '',
 checked_in BOOLEAN NOT NULL DEFAULT 0,
 fair_play_at DATETIME NOT NULL,
 UNIQUE KEY event_game (event_id, game_id),
 UNIQUE KEY event_user (event_id, user_id),
 FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE,
 FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS teams (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 event_id INT UNSIGNED NOT NULL,
 name VARCHAR(80) NOT NULL,
 captain_id INT UNSIGNED NULL,
 color VARCHAR(12) NOT NULL DEFAULT '#9d7bff',
 UNIQUE KEY event_name (event_id, name),
 FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE,
 FOREIGN KEY (captain_id) REFERENCES players(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS team_members (
 team_id INT UNSIGNED NOT NULL,
 player_id INT UNSIGNED NOT NULL UNIQUE,
 PRIMARY KEY (team_id, player_id),
 FOREIGN KEY (team_id) REFERENCES teams(id) ON DELETE CASCADE,
 FOREIGN KEY (player_id) REFERENCES players(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS join_requests (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 team_id INT UNSIGNED NOT NULL,
 player_id INT UNSIGNED NOT NULL,
 UNIQUE KEY team_player (team_id, player_id),
 FOREIGN KEY (team_id) REFERENCES teams(id) ON DELETE CASCADE,
 FOREIGN KEY (player_id) REFERENCES players(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS matches (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 event_id INT UNSIGNED NOT NULL,
 round_no SMALLINT UNSIGNED NOT NULL,
 team_a INT UNSIGNED NOT NULL,
 team_b INT UNSIGNED NOT NULL,
 score_a TINYINT UNSIGNED NULL,
 score_b TINYINT UNSIGNED NULL,
 status ENUM('scheduled','pending','confirmed') NOT NULL DEFAULT 'scheduled',
 submitted_by INT UNSIGNED NULL,
 confirmed_by INT UNSIGNED NULL,
 submitted_at DATETIME NULL,
 confirmed_at DATETIME NULL,
 FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE,
 FOREIGN KEY (team_a) REFERENCES teams(id),
 FOREIGN KEY (team_b) REFERENCES teams(id),
 FOREIGN KEY (submitted_by) REFERENCES users(id),
 FOREIGN KEY (confirmed_by) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS audit_log (
 id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
 event_id INT UNSIGNED NULL,
 user_id INT UNSIGNED NULL,
 action VARCHAR(1000) NOT NULL,
 created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
 FOREIGN KEY (event_id) REFERENCES events(id) ON DELETE CASCADE,
 FOREIGN KEY (user_id) REFERENCES users(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS rate_limits (
 bucket_key CHAR(64) PRIMARY KEY,
 window_start BIGINT UNSIGNED NOT NULL,
 hits INT UNSIGNED NOT NULL,
 expires_at BIGINT UNSIGNED NOT NULL,
 INDEX (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS email_verifications (
 user_id INT UNSIGNED PRIMARY KEY,
 code_hash CHAR(64) NOT NULL,
 expires_at DATETIME NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS web_sessions (
 id_hash CHAR(64) PRIMARY KEY,
 payload MEDIUMBLOB NOT NULL,
 expires_at BIGINT UNSIGNED NOT NULL,
 INDEX (expires_at)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;

CREATE TABLE IF NOT EXISTS password_resets (
 user_id INT UNSIGNED PRIMARY KEY,
 password_hash VARCHAR(255) NOT NULL,
 expires_at DATETIME NOT NULL,
 FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4;
